// 电脑上的操作：WASD 走、Shift+1 2 3 升级技能、K 补刀、L 推塔、1 2 3 朝鼠标放技能、F 朝鼠标闪现、H 恢复、B 回城、P 暂停。每一步检查对局状态。
// 用法：node test/keys.js [输出目录]
const path = require('path'), fs = require('fs');
const { ROOT, launch, watchErrors } = require('./lib');
(async () => {
  const out = process.argv[2] || 'shots-keys';
  fs.mkdirSync(out, { recursive: true });
  const { browser, ctx } = await launch({ viewport: { width: 1280, height: 720 }, deviceScaleFactor: 1 });
  const page = await ctx.newPage();
  const errs = watchErrors(page);
  await page.goto('file://' + path.join(ROOT, '峡谷争锋.html'));
  await page.waitForSelector('#title:not([hidden])', { timeout: 60000 });
  await page.evaluate(() => { G.perf.off = true; });
  const click = async sel => { const b = await (await page.$(sel)).boundingBox(); await page.mouse.click(b.x + b.width / 2, b.y + b.height / 2); };
  await click('#bStart'); await page.waitForSelector('#select:not([hidden])');
  await click('.card[data-h="mage"]'); await click('#bGo');
  await page.waitForFunction(() => G.scr === 'game', null, { timeout: 30000 });
  await page.evaluate(() => { for (let i = 0; i < 60 * 30; i++) { step(G.W, 1 / 60); G.W.ev.length = 0; } G.me.lvl = 4; G.me.skillPts = 4; });
  const run = s => page.evaluate(s => { for (let i = 0; i < s * 60; i++) { playerCmd(G.W, G.me); step(G.W, 1 / 60); G.W.ev.length = 0; } }, s);
  const st = () => page.evaluate(() => ({ x: Math.round(G.me.x), y: Math.round(G.me.y), cd: G.me.sk.map(k => +k.cd.toFixed(1)), flash: Math.round(G.me.flashCd), heal: Math.round(G.me.healCd), recall: G.me.recall, scr: G.scr, kb: HUD.keyboard }));
  const res = [];
  const ok = (name, cond, info) => { res.push(!!cond); console.log((cond ? 'OK  ' : 'FAIL') + ' ' + name + (info ? '  ' + JSON.stringify(info) : '')); };
  for (const k of ['1', '2', '3']) await page.keyboard.press('Shift+Digit' + k);
  let sr = await page.evaluate(() => ({ rank: G.me.sk.map(k => k.rank), pts: G.me.skillPts }));
  ok('Shift+1 2 3：三个技能各升一级', sr.rank.join() === '1,1,1' && sr.pts === 1, sr);
  await page.keyboard.down('KeyK'); await run(0.05);
  sr = await page.evaluate(() => G.me.cmd.atkMode + '/' + G.me.cmd.atkAuto);
  await page.keyboard.up('KeyK');
  ok('K：补刀（只打小兵野怪）', sr === 'minion/true', sr);
  await page.keyboard.down('KeyL'); await run(0.05);
  sr = await page.evaluate(() => G.me.cmd.atkMode + '/' + G.me.cmd.atkAuto);
  await page.keyboard.up('KeyL');
  ok('L：推塔（只打塔）', sr === 'tower/true', sr);
  let s0 = await st();
  await page.keyboard.down('KeyD'); await page.keyboard.down('KeyW');
  await run(1.5);
  await page.keyboard.up('KeyD'); await page.keyboard.up('KeyW');
  let s1 = await st();
  ok('D + W：往右上走', s1.x - s0.x > 150 && s0.y - s1.y > 150, { from: [s0.x, s0.y], to: [s1.x, s1.y] });
  ok('提示一行键位（电脑上）', s1.kb);
  // 鼠标放到英雄右边，按 1：星火球朝右飞
  const scr = await page.evaluate(() => { const o = [0, 0, 0]; worldToScreen(G.me.x + 400, 0, G.me.y, o); return o; });
  await page.mouse.move(scr[0], scr[1]);
  await page.waitForTimeout(300);
  await page.keyboard.press('Digit1');
  await run(0.05);                     // 技能在下一步模拟里才放出去
  const proj = await page.evaluate(() => { const p = G.W.projs.find(q => q.on === 'm1'); return p ? { dx: +p.dx.toFixed(2), dy: +p.dy.toFixed(2) } : null; });
  s1 = await st();
  ok('按 1：技能朝鼠标放（往右）', s1.cd[0] > 0 && proj && proj.dx > 0.9, { cd: s1.cd, proj });
  await page.keyboard.press('Digit2'); await run(0.05);
  s1 = await st();
  ok('按 2：冰晶环', s1.cd[1] > 0, s1.cd);
  await page.keyboard.press('Digit3'); await run(0.05);
  s1 = await st();
  ok('按 3：流星雨', s1.cd[2] > 0, s1.cd);
  await page.screenshot({ path: path.join(out, 'k1-skills.png') });
  s0 = await st();
  await page.keyboard.press('KeyF'); await run(0.05);
  s1 = await st();
  ok('F：朝鼠标闪现', s1.flash > 0 && s1.x - s0.x > 200, { from: [s0.x, s0.y], to: [s1.x, s1.y] });
  await page.keyboard.press('KeyH'); await run(0.05);
  s1 = await st();
  ok('H：恢复', s1.heal > 0, s1);
  await page.keyboard.press('KeyB'); await run(0.2);
  s1 = await st();
  ok('B：回城', s1.recall > 0, s1);
  await page.keyboard.press('KeyP');
  s1 = await st();
  ok('P：暂停', s1.scr === 'pause', s1.scr);
  await page.keyboard.press('KeyP');
  s1 = await st();
  ok('再按 P：继续', s1.scr === 'game', s1.scr);
  await page.waitForTimeout(600);
  await page.screenshot({ path: path.join(out, 'k2-desktop.png') });
  const bad = res.filter(r => !r).length;
  console.log(`\n${res.length - bad}/${res.length} 通过`);
  console.log(errs.length ? errs.join('\n') : 'no errors');
  await browser.close();
  process.exit(bad ? 1 : 0);
})();
